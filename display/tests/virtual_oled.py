"""PC-side virtual 128x64 monochrome "OLED" -- implements the same
fill/pixel/fill_rect/hline/vline/line/text/show duck-typed surface
display_ui.DisplayUI expects from a canvas, backed by a plain Python list
of lists (no machine/framebuf import, so this runs under any CPython).

Used by the test suite (test_display_ui.py, test_oled_device.py) and by
examples/hand_demo.py's PC entry point to produce PNG previews without
real hardware -- see README.md "PC에서 가상 화면을 확인하는 방법".

text() now renders the *exact* bitmap font and pixel algorithm that
MicroPython's own framebuf.FrameBuffer.text() uses (see FONT_8X8 below).
This was verified by reading MicroPython's upstream source directly, not
by comparing against real hardware (none is available this session) --
see README.md / DEVELOPMENT.md for how that verification was done and its
limits. line() is a standard Bresenham implementation.
"""

