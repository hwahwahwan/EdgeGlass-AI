_FONT_W = 8  # matches framebuf.FrameBuffer's fixed-width bitmap font
_FONT_H = 8


class VirtualOLED:
    def __init__(self, width=128, height=64):
        self.width = width
        self.height = height
        self.pixels = [[0] * width for _ in range(height)]
        self.show_count = 0

    def fill(self, col):
        for row in self.pixels:
            for x in range(self.width):
                row[x] = col

    def pixel(self, x, y, col=None):
        if not (0 <= x < self.width and 0 <= y < self.height):
            return None
        if col is None:
            return self.pixels[y][x]
        self.pixels[y][x] = 1 if col else 0
        return None

    def fill_rect(self, x, y, w, h, col):
        for yy in range(max(y, 0), min(y + h, self.height)):
            for xx in range(max(x, 0), min(x + w, self.width)):
                self.pixels[yy][xx] = 1 if col else 0

    def rect(self, x, y, w, h, col):
        self.hline(x, y, w, col)
        self.hline(x, y + h - 1, w, col)
        self.vline(x, y, h, col)
        self.vline(x + w - 1, y, h, col)

    def hline(self, x, y, w, col):
        self.fill_rect(x, y, w, 1, col)

    def vline(self, x, y, h, col):
        self.fill_rect(x, y, 1, h, col)

    def line(self, x1, y1, x2, y2, col):
        x1, y1, x2, y2 = int(x1), int(y1), int(x2), int(y2)
        dx = abs(x2 - x1)
        dy = -abs(y2 - y1)
        sx = 1 if x1 < x2 else -1
        sy = 1 if y1 < y2 else -1
        err = dx + dy
        x, y = x1, y1
        while True:
            self.pixel(x, y, col)
            if x == x2 and y == y2:
                break
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x += sx
            if e2 <= dx:
                err += dx
                y += sy

    def text(self, string, x, y, col=1):
        # Ported 1:1 from MicroPython's extmod/modframebuf.c framebuf_text():
        # x0 is a running cursor advanced inside the column loop (not reset
        # per character), each glyph is 8 columns, and within a column byte
        # bit 0 is the top pixel, counting down as the byte is shifted right.
        x0 = x
        for ch in string:
            code = ord(ch)
            if code < 32 or code > 127:
                code = 127
            glyph = FONT_8X8[(code - 32) * 8:(code - 32) * 8 + 8]
            for j in range(_FONT_W):
                xx = x0 + j
                if 0 <= xx < self.width:
                    vline = glyph[j]
                    yy = y
                    while vline:
                        if vline & 1 and 0 <= yy < self.height:
                            self.pixels[yy][xx] = 1 if col else 0
                        vline >>= 1
                        yy += 1
            x0 += _FONT_W

    def scroll(self, dx, dy):
        raise NotImplementedError("scroll() is not used by display_ui.py; not faked here")

    def show(self):
        self.show_count += 1

    def to_png(self, path, scale=6, on_color=(255, 255, 255), off_color=(12, 12, 12)):
        """Save the current buffer as a PNG, nearest-neighbor scaled up so
        individual pixels stay visible. Requires Pillow (see
        requirements.txt). Returns ``path``."""
        from PIL import Image

        img = Image.new("RGB", (self.width, self.height), off_color)
        px = img.load()
        for y in range(self.height):
            for x in range(self.width):
                if self.pixels[y][x]:
                    px[x, y] = on_color
        img = img.resize((self.width * scale, self.height * scale), Image.NEAREST)
        img.save(path)
        return path
